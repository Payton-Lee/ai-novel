OUTLINE_STRUCTURE = """## 全书大纲

### 核心主线
- 一句话主线 (主角的欲望 + 核心障碍)
- 主角成长弧线 (起点 → 转变 → 终点)
- 结局指向 (读者期待什么)

### 分卷规划
每卷:
- 卷名 / 卷主题
- 卷目标 (这一卷要推进什么)
- 起承转合四拍 (本卷的高潮与转折)
- 卷末大钩子 (驱动读者进入下一卷)

### 分章大纲
每一章:
- 章节序号 + 标题
- 核心事件 (本章发生什么)
- 冲突 (谁和谁的对抗 / 主角内心的矛盾)
- 章末钩子 (结尾的悬念)
- 涉及人物
- 伏笔: 埋设 / 回收
"""

# ============================================================
# 规划方法论
# ============================================================

PLANNING_METHODOLOGY = """## 大纲规划方法论 (必须遵守)

1. **主线贯穿**: 主角的欲望 (来自需求) 和障碍 (来自冲突) 必须贯穿全书, 每一卷都推动主线前进, 不能偏离。
2. **起承转合**: 每卷遵循起承转合; 卷末必须有大钩子, 章末必须有小钩子。
3. **钩子分级**: 章末小钩子 / 卷末大钩子 / 全书终局, 三个层级的悬念不能互相替代。
4. **伏笔网络**: 每章明确标注埋设与回收的伏笔, 防止伏笔丢失或忘记回收。
5. **节奏控制**: 小爽点每 3-5 章一个, 卷内有中型高潮, 每卷末大爽点; 避免连续两三章都是平缓过渡。
6. **每章有用**: 每一章必须推进主线或人物成长, 杜绝注水章、凑字章。
7. **闭环检查**: 大纲要能回答 — 主角的"需求 → 障碍 → 突破"链条是否清晰成立? 冲突是否升级? 看点在持续?
"""

