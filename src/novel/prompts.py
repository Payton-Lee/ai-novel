"""所有 Agent 的系统提示词 — 含禁词表、风格指令、去AI味策略.

提示词设计原则:
1. 每个 Agent 有明确的职责边界和输出格式要求
2. 禁词表嵌入到写作相关 Agent 的提示词中, 从源头避免 AI 味
3. 强调"展示而非告知" (show not tell) 的写作原则
4. 模拟人类网文写手的创作习惯
"""

